export const CAREER_CATEGORIES: CareerCategory[] = rows.map(
  ([id, name, stat, groups, nodes, practice, project]) => ({
    id,
    name,
    stat,
    groups,
    nodes: nodes as CareerCategory["nodes"],
    practice,
    project,
    focuses: (
      focusRows[id] || [
        [`${id}-practice`, name.split(" & ")[0], practice, project],
      ]
    ).map(([id, name, practice, project]) => ({ id, name, practice, project })),
  }),
);
export const VOCATIONS = CAREER_CATEGORIES.flatMap((c) =>
  c.focuses.map((f) => ({ ...f, category: c.id })),
);
export function careerCategory(role: string): CareerCategory {
  if (/account|financ|audit|budget|credit|tax|investment|bookkeep/i.test(role))
    return CAREER_CATEGORIES.find((c) => c.id === "finance")!;
  if (/marketing|market research|public relations/i.test(role))
    return CAREER_CATEGORIES.find((c) => c.id === "sales")!;
  const code = professionGroup(role).code;
  return (
    CAREER_CATEGORIES.find((c) => c.groups.includes(code)) ||
    CAREER_CATEGORIES[19]
  );
}
